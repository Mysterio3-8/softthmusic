"""Один тик за раз. Замок на файле, без внешних зависимостей.

🔴 Оплачено живой поломкой 17.08. Таймер тикает каждые 15 минут, а сборка сборника идёт
25–30: тики накладывались, и в один рабочий каталог писали сразу три процесса. Пока
сегменты назывались финальными именами, они просто перезаписывали друг друга и это
сходило с рук; после перехода на атомарную запись (`seg_001.part.mp4` → переименование)
`finally` одного процесса стал удалять временный файл, который в этот момент писал
другой — ffmpeg падал с «Unable to re-open output file for shifting data», и сборник не
собирался вовсе.

Наложение вредно и само по себе: на одном ядре и 961 МБ два ffmpeg-рендера конкурируют
за процессор и память, то есть оба идут вдвое дольше и приближают убийство юнита по
таймауту — ровно то, из-за чего сборники стояли двое суток.

Почему файл, а не `flock`: `fcntl` есть только на Unix, а тесты гоняются на Windows.
Пары «создать эксклюзивно + время жизни» здесь достаточно: процесс один, гонки за
миллисекунды нет, а зависший замок не должен блокировать поток навсегда.
"""
from __future__ import annotations

import os
import time
from pathlib import Path

STALE_AFTER_SECONDS = 3 * 60 * 60
"""Через сколько замок считается брошенным.

Три часа — заведомо больше самой долгой честной работы (скачать 15 треков и отрендерить
их на одном ядре — до получаса), но меньше суток, чтобы убитый по SIGKILL процесс не
остановил поток до вмешательства человека. `finally` при SIGKILL не выполняется, поэтому
замок обязан протухать сам."""


class AlreadyRunning(Exception):
    """Другой тик ещё работает. Не ошибка: расписание периодическое, вернёмся позже."""


def acquire(lock_path: Path, stale_after: int = STALE_AFTER_SECONDS) -> Path:
    """Занять замок. Бросает `AlreadyRunning`, если он занят живым процессом."""
    lock_path.parent.mkdir(parents=True, exist_ok=True)
    try:
        fd = os.open(lock_path, os.O_CREAT | os.O_EXCL | os.O_WRONLY)
    except FileExistsError:
        age = time.time() - lock_path.stat().st_mtime
        # `stale_after <= 0` означает «забрать в любом случае». Сравнения одного age с
        # порогом мало: время файла бывает на доли секунды в будущем (гранулярность
        # файловой системы), и тогда возраст отрицательный, а замок — «свежий навсегда».
        if stale_after > 0 and age < stale_after:
            raise AlreadyRunning(
                f"тик уже идёт {int(age // 60)} мин (замок {lock_path.name})"
            ) from None
        # Замок протух — забираем его себе. Перезаписываем, а не удаляем и создаём
        # заново: между удалением и созданием влез бы третий процесс.
        fd = os.open(lock_path, os.O_CREAT | os.O_WRONLY | os.O_TRUNC)
    with os.fdopen(fd, "w") as handle:
        handle.write(str(os.getpid()))
    return lock_path


def release(lock_path: Path) -> None:
    """Снять замок. Отсутствие файла не ошибка — его мог забрать протухшим другой тик."""
    Path(lock_path).unlink(missing_ok=True)
